"""
Langue des documents générés côté serveur (PDF, exports).

Lit ``PharmacySettings.locale`` ('fr-FR', 'en-US', ...) et expose un petit
dictionnaire de traductions pour les chaînes écrites dans les documents.

Usage::

    from api.utils_doclang import T, get_document_language

    lang = get_document_language()          # 'fr' ou 'en'
    titre = T(lang, 'doc_report')           # 'RAPPORT' ou 'REPORT'
    label = T(lang, 'title_rapport_mensuel', mois='2026-01')

Aucune dépendance à django.utils.translation : le dict simple suffit.
"""


def get_document_language() -> str:
    """
    Retourne 'en' si ``PharmacySettings.locale`` commence par 'en', sinon 'fr'.

    Robuste : toute erreur (DB inaccessible, settings absents, champ manquant)
    retombe sur 'fr'.
    """
    try:
        from api.models import PharmacySettings
        ps = PharmacySettings.objects.first()
        locale = (getattr(ps, 'locale', None) or 'fr-FR') if ps else 'fr-FR'
        return 'en' if str(locale).strip().lower().startswith('en') else 'fr'
    except Exception:
        return 'fr'


