def T(lang: str, key: str, **kwargs) -> str:
    """
    Retourne la chaîne traduite pour ``key`` dans ``lang``.

    Fallback : table 'fr', puis la clé elle-même si absente partout.
    Les placeholders ``{nom}`` sont remplacés via ``**kwargs`` (str.format).
    """
    table = DOC_STRINGS.get(lang) or DOC_STRINGS['fr']
    s = table.get(key, DOC_STRINGS['fr'].get(key, key))
    if kwargs:
        try:
            return s.format(**kwargs)
        except Exception:
            return s
    return s


def format_doc_date(value, lang: str = 'fr', with_time: bool = False) -> str:
    """
    Formate une date/datetime selon la langue du document :
    ``jj/mm/aaaa`` en français, ``mm/dd/yyyy`` en anglais.

    Retourne ``str(value)`` en dernier recours.
    """
    fmt = '%m/%d/%Y' if lang == 'en' else '%d/%m/%Y'
    if with_time:
        fmt += ' %H:%M'
    try:
        return value.strftime(fmt)
    except Exception:
        return str(value)
